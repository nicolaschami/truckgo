import 'dart:async';
import 'dart:convert';
import 'dart:io';

import 'package:http/http.dart' as http;

import '../mock_vehicles.dart';

/// Where the TruckGo API is.
///
/// Default: the developer's PC, reached from a phone on USB after
///   adb reverse tcp:5000 tcp:5000
/// (the phone's "localhost:5000" then goes to the PC's port 5000).
/// Another server:
///   flutter run --dart-define=API_URL=https://api.example.com
const apiUrl = String.fromEnvironment(
  'API_URL',
  defaultValue: 'http://localhost:5000',
);

/// What went wrong with a call, so each screen can say the right thing.
enum ApiErrorKind {
  offline, // no network, server down, or too slow: try again later
  unauthorized, // wrong PIN, locked, or the login expired: log in again
  rejected, // the server refused the request (e.g. unknown truck)
  server, // the server failed: not the driver's fault
}

class ApiException implements Exception {
  ApiException(this.kind, this.message);

  final ApiErrorKind kind;

  /// A sentence for the driver (the server's own explanation when it gave one).
  final String message;

  @override
  String toString() => message;
}

/// The answer to a successful login.
class LoginResult {
  const LoginResult({
    required this.accessToken,
    required this.displayName,
    required this.mustChangePin,
  });

  final String accessToken;
  final String displayName;

  /// The PIN was generated by the office: the driver must choose their own.
  final bool mustChangePin;
}

/// The answer to "deliveries of my truck" (see DeliveriesResponse on the server).
class TruckDeliveries {
  const TruckDeliveries({
    required this.serverTime,
    required this.deliveries,
    required this.removed,
  });

  /// Send this back as `since` next time ("what changed after this?").
  final DateTime serverTime;

  /// New or changed deliveries, as the server sent them (JSON objects).
  /// All of the truck's deliveries when there was no `since`.
  final List<Map<String, dynamic>> deliveries;

  /// Keys ("plant/number") of deliveries taken off the truck since then.
  final List<String> removed;
}

/// The only place the app talks to the TruckGo server.
///
/// Every method returns the server's answer or throws an [ApiException];
/// nothing here touches the phone's database (DeliverySync does that).
class ApiClient {
  ApiClient._();

  static final ApiClient instance = ApiClient._();

  /// Tests replace this with a fake server.
  http.Client httpClient = http.Client();

  /// The login token, sent with every call after login. Restored from the
  /// database at start-up by SessionStore.
  String? token;

  static const _timeout = Duration(seconds: 15);

  /// Checks the username and PIN. Does not keep the token: the caller saves
  /// it (SessionStore.login), so it survives an app restart.
  Future<LoginResult> login(String username, String pin) async {
    final json = await _send('POST', '/auth/login',
        body: {'username': username, 'pin': pin}, withToken: false);
    return LoginResult(
      accessToken: json['accessToken'] as String,
      displayName: (json['driver'] as Map<String, dynamic>)['displayName'] as String,
      mustChangePin: json['mustChangePin'] as bool,
    );
  }

  /// The company's active trucks and trailers, for the truck selection.
  Future<List<Vehicle>> vehicles() async {
    final json = await _send('GET', '/vehicles') as List<dynamic>;
    return [
      for (final v in json.cast<Map<String, dynamic>>())
        Vehicle(
          plate: v['plate'] as String,
          isTruck: v['isTruck'] as bool,
          model: v['model'] as String,
          detail: v['detail'] as String,
          status: VehicleStatus.values.byName(v['status'] as String),
        ),
    ];
  }

  /// The deliveries of [truckPlate]: all of them, or with [since] only what
  /// changed after that moment (plus the ones taken off the truck).
  Future<TruckDeliveries> truckDeliveries(String truckPlate,
      {DateTime? since}) async {
    final query = since == null
        ? ''
        : '?since=${Uri.encodeQueryComponent(since.toUtc().toIso8601String())}';
    final json = await _send('GET',
        '/trucks/${Uri.encodeComponent(truckPlate)}/deliveries$query');

    return TruckDeliveries(
      serverTime: DateTime.parse(json['serverTime'] as String),
      deliveries:
          (json['deliveries'] as List<dynamic>).cast<Map<String, dynamic>>(),
      removed: [
        for (final r in (json['removed'] as List<dynamic>)
            .cast<Map<String, dynamic>>())
          '${r['plantCode']}/${r['number']}',
      ],
    );
  }

  // ---------------------------------------------------------------
  // ONE CALL: send, wait (at most 15 s), turn every failure into an
  // ApiException the screens understand
  // ---------------------------------------------------------------

  Future<dynamic> _send(String method, String path,
      {Object? body, bool withToken = true}) async {
    final request = http.Request(method, Uri.parse('$apiUrl/api/v1$path'));
    request.headers['Accept'] = 'application/json';
    if (withToken && token != null) {
      request.headers['Authorization'] = 'Bearer $token';
    }
    if (body != null) {
      request.headers['Content-Type'] = 'application/json';
      request.body = jsonEncode(body);
    }

    final http.Response response;
    try {
      response = await http.Response.fromStream(
          await httpClient.send(request).timeout(_timeout));
    } on TimeoutException {
      throw ApiException(ApiErrorKind.offline, 'The server does not answer.');
    } on SocketException {
      throw ApiException(ApiErrorKind.offline, 'No connection to the server.');
    } on http.ClientException {
      throw ApiException(ApiErrorKind.offline, 'No connection to the server.');
    }

    final code = response.statusCode;
    if (code >= 200 && code < 300) {
      return response.body.isEmpty ? null : jsonDecode(response.body);
    }

    // The server explains its refusals in "detail" (ASP.NET problem details)
    final detail = _detail(response.body);
    if (code == 401) {
      throw ApiException(ApiErrorKind.unauthorized,
          detail ?? 'Your login has expired. Please log in again.');
    }
    if (code >= 500) {
      throw ApiException(ApiErrorKind.server,
          'The server had a problem. Please try again later.');
    }
    throw ApiException(
        ApiErrorKind.rejected, detail ?? 'The server refused the request ($code).');
  }

  static String? _detail(String body) {
    try {
      final json = jsonDecode(body);
      if (json is Map<String, dynamic>) {
        return (json['detail'] ?? json['title']) as String?;
      }
    } catch (_) {
      // Not JSON: no explanation to show
    }
    return null;
  }
}
