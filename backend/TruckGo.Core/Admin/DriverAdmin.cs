using System.Text.RegularExpressions;
using Microsoft.AspNetCore.Identity;
using Microsoft.EntityFrameworkCore;
using TruckGo.Data;

namespace TruckGo.Admin;

/// <summary>One line of the Drivers screen.</summary>
public record DriverRow(
    Guid Id,
    string Username,
    string DisplayName,
    string? Phone,
    bool IsActive,
    bool IsLocked,
    bool MustChangePin,
    DateTime? LastLoginAt,
    string? LastDeviceId);

/// <summary>
/// Driver accounts for the app (docs/back-office-design.md, screen 4).
/// Drivers are TruckGo's own data: created, edited, reset, unlocked and
/// deactivated in the back office — never deleted, so deliveries and traces
/// keep their name.
///
/// The PIN is 4 digits, GENERATED by TruckGo (never typed by the office),
/// shown once, stored only as a hash. The driver must choose their own PIN
/// at the next login (the app calls ChangePinAsync).
///
/// Every office method works inside ONE company; each call opens its own
/// short database context (the Blazor Server pattern, see UserAdmin).
/// </summary>
public partial class DriverAdmin(IDbContextFactory<TruckGoDb> dbFactory, TimeProvider clock)
{
    private readonly PasswordHasher<Driver> _hasher = new();
    private DateTime Now => clock.GetUtcNow().UtcDateTime;

    // ------------------------------------------------------------------
    // The Drivers screen (Admin or Dispatcher)
    // ------------------------------------------------------------------

    /// <summary>All drivers of the company, active first, then by name.</summary>
    public async Task<List<DriverRow>> ListAsync(Guid companyId)
    {
        await using var db = await dbFactory.CreateDbContextAsync();
        var now = Now;
        return await db.Drivers
            .Where(d => d.CompanyId == companyId)
            .OrderByDescending(d => d.IsActive).ThenBy(d => d.DisplayName)
            .Select(d => new DriverRow(d.Id, d.Username, d.DisplayName, d.Phone, d.IsActive,
                d.LockedUntil != null && d.LockedUntil > now, d.MustChangePin, d.LastLoginAt, d.LastDeviceId))
            .ToListAsync();
    }

    /// <summary>
    /// Creates a driver with a generated 4-digit PIN. Returns the PIN so the
    /// screen can show it ONCE; it is never shown again.
    /// </summary>
    public async Task<string> CreateAsync(Guid companyId, string username, string displayName, string? phone)
    {
        username = NormalizeUsername(username);
        if (!UsernamePattern().IsMatch(username))
            throw new AdminException("The username must be 3 to 30 letters or digits, without spaces.");
        if (string.IsNullOrWhiteSpace(displayName)) throw new AdminException("Please enter the driver's name.");

        await using var db = await dbFactory.CreateDbContextAsync();
        // Unique on the whole server: the app's login does not ask for a company
        if (await db.Drivers.AnyAsync(d => d.Username == username))
            throw new AdminException("This username is already used.");

        var pin = Secrets.DriverPin();
        var driver = new Driver
        {
            Id = Guid.NewGuid(), CompanyId = companyId, Username = username, PinHash = "",
            DisplayName = displayName.Trim(), Phone = Clean(phone), MustChangePin = true,
        };
        driver.PinHash = _hasher.HashPassword(driver, pin);
        db.Drivers.Add(driver);
        await db.SaveChangesAsync();
        return pin;
    }

    /// <summary>Changes name and phone. The username (login) never changes.</summary>
    public async Task UpdateAsync(Guid companyId, Guid driverId, string displayName, string? phone)
    {
        if (string.IsNullOrWhiteSpace(displayName)) throw new AdminException("Please enter the driver's name.");

        await using var db = await dbFactory.CreateDbContextAsync();
        var driver = await FindAsync(db, companyId, driverId);
        driver.DisplayName = displayName.Trim();
        driver.Phone = Clean(phone);
        await db.SaveChangesAsync();
    }

    /// <summary>
    /// Gives the driver a new generated PIN (forgotten PIN). Also unlocks the
    /// account. Returns the PIN to show ONCE.
    /// </summary>
    public async Task<string> ResetPinAsync(Guid companyId, Guid driverId)
    {
        await using var db = await dbFactory.CreateDbContextAsync();
        var driver = await FindAsync(db, companyId, driverId);

        var pin = Secrets.DriverPin();
        driver.PinHash = _hasher.HashPassword(driver, pin);
        driver.MustChangePin = true;
        driver.FailedLogins = 0;
        driver.LockedUntil = null;
        await db.SaveChangesAsync();
        return pin;
    }

    /// <summary>Lifts the lock after too many wrong PINs, without changing the PIN.</summary>
    public async Task UnlockAsync(Guid companyId, Guid driverId)
    {
        await using var db = await dbFactory.CreateDbContextAsync();
        var driver = await FindAsync(db, companyId, driverId);
        driver.FailedLogins = 0;
        driver.LockedUntil = null;
        await db.SaveChangesAsync();
    }

    /// <summary>Deactivates (no more login in the app) or reactivates a driver. Never deleted.</summary>
    public async Task SetActiveAsync(Guid companyId, Guid driverId, bool active)
    {
        await using var db = await dbFactory.CreateDbContextAsync();
        var driver = await FindAsync(db, companyId, driverId);
        driver.IsActive = active;
        await db.SaveChangesAsync();
    }

    // ------------------------------------------------------------------
    // The app: the driver chooses their own PIN
    // ------------------------------------------------------------------

    /// <summary>
    /// The driver replaces their PIN (forced after a generated one). Needs
    /// the current PIN. The new one: 4 digits, not all the same, different
    /// from the current one.
    /// </summary>
    public async Task ChangePinAsync(Guid driverId, string currentPin, string newPin)
    {
        await using var db = await dbFactory.CreateDbContextAsync();
        var driver = await db.Drivers.SingleAsync(d => d.Id == driverId);

        if (_hasher.VerifyHashedPassword(driver, driver.PinHash, currentPin) == PasswordVerificationResult.Failed)
            throw new AdminException("The current PIN is not correct.");
        if (!PinPattern().IsMatch(newPin))
            throw new AdminException("The new PIN must be exactly 4 digits.");
        if (newPin.Distinct().Count() == 1)
            throw new AdminException("The new PIN cannot be the same digit four times.");
        if (newPin == currentPin)
            throw new AdminException("The new PIN must be different from the current one.");

        driver.PinHash = _hasher.HashPassword(driver, newPin);
        driver.MustChangePin = false;
        await db.SaveChangesAsync();
    }

    // ------------------------------------------------------------------

    /// <summary>Usernames are compared in lower case without spaces: "Test1 " = "test1".</summary>
    public static string NormalizeUsername(string username) => username.Trim().ToLowerInvariant();

    [GeneratedRegex("^[a-z0-9]{3,30}$")]
    private static partial Regex UsernamePattern();

    [GeneratedRegex("^[0-9]{4}$")]
    private static partial Regex PinPattern();

    private static string? Clean(string? value) => string.IsNullOrWhiteSpace(value) ? null : value.Trim();

    // Finding the driver INSIDE the company is what keeps companies apart
    private static async Task<Driver> FindAsync(TruckGoDb db, Guid companyId, Guid driverId) =>
        await db.Drivers.FirstOrDefaultAsync(d => d.Id == driverId && d.CompanyId == companyId)
        ?? throw new AdminException("This driver does not exist.");
}
